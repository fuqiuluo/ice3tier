//! relay。
//!
//! relay 只转发包：节点先和它建一个中转会话，之后带着中转头的数据报被原样送到目的节点的会话上；
//! 中转头里写着好几个 relay 时，送到路径上下一个 relay 的会话上。它不解密（也解不开）、不重传、不为流记状态，发不出去就丢。
//!
//! 别的 relay 在它上面建的会话就是骨干上的连接，走 UDP，两个 relay 之间 UDP 不通时走一条 TCP（[`i3t_path::backbone`]）。
//! 骨干延迟矩阵由路径层来测，relay 这边只负责给自己的那一行签名、把各行发给所有会话；过载和即将下线的通知用的是同一种帧。
//!
//! | 模块 | 内容 |
//! |---|---|
//! | [`relay`] | 握手、保活、转发，以及跟随 netmap 的启用与停用 |
//! | `leg` | 同一个端口号上的 TCP 中转 |
//! | `session` | 会话表 |
//! | `cookie` | 握手里不记状态的地址证明 |
//! | `limit` | 带宽上限和它在来源节点之间的分配，错误帧和握手的限速 |
//! | [`counters`] | 计数 |
//!
//! # 对没有认证过的来源
//!
//! - 握手的每一步应答都不比请求大，来源地址得到证明（cookie）之前不记状态、不验签名。格式上的保证见 [`i3t_proto::session`]。
//! - cookie 证明了地址，但一个 cookie 可以反复用：验签名之前再按来源（IPv4 地址或者 IPv6 的 /64）限速，另有一个总数的上限。
//! - 没有会话的来源发来的中转帧被丢掉，只按来源地址限速地回一个 14 字节的错误帧；请求比它短就不回。
//!   错误帧回显请求里路径外的人猜不到的字节（规则见 [`i3t_proto::session`]），节点靠它分辨真假。
//! - TCP 上没有握手成功的连接：从接受时算起 10 秒之内必须握手成功，这之前只收 INIT 和 AUTH，同一个来源同时最多 8 条。
//!   握手成功之后会话又没了的连接，从发现会话没了算起也是 10 秒；这两个时限都不因为来了帧而延长。
//! - 同一个 TCP 端口还接 ice3proxy 时（[`Relay::set_tcp_handoff`]），先看连接的第一个字节：3 秒之内不来的断开，
//!   还没认出来的连接同一个来源最多 256 条、全部最多 1024 条；认出来是中转的再走上面那一条。
//! - 配置带宽上限后，将在各来源节点间公平分配；单个成员突发流量不会侵占其他节点份额，也不会导致 relay 向全体节点宣告过载。
//! - 多级中转的帧只认路径上前一站发来的（排第一的认来源节点的会话，排在后面的认前一个 relay 的会话：它绑定的那个 UDP 地址或者那条 TCP），
//!   路径上没有本节点、比网络允许的级数长、想绕圈的一律不转发；不照办时只有排第一的 relay 回错误帧。
//! - 签名无效、cookie 无效、节点不在允许列表或未知类型的帧一律静默丢弃，不作回应。

