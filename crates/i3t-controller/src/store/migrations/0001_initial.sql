-- 最初的表结构：网络、分组、节点、注册令牌、规则、代理、端口转发、节点对设置、冷却期、操作记录、
-- 主动测试的结果、换路的历史、画图用的时间序列。
--
-- 列的写法见 schema.rs。编号用 IDENTITY：序列只往前走，删掉的行的编号不会再分给别人。

CREATE TABLE meta (
    key   TEXT PRIMARY KEY,
    value BYTEA NOT NULL
);

CREATE TABLE networks (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                    TEXT NOT NULL UNIQUE,
    cidr                    TEXT NOT NULL,
    routing                 JSONB NOT NULL,
    max_relay_hops          BIGINT NOT NULL,
    reach                   JSONB NOT NULL,
    created_at              BIGINT NOT NULL,
    class                   JSONB,
    ack_eliciting_threshold BIGINT NOT NULL,
    max_ack_delay_ms        BIGINT NOT NULL,
    bundle_small_packets    BOOLEAN NOT NULL,
    vnet_offload            BOOLEAN NOT NULL,
    vnet_mtu                BIGINT NOT NULL
);

-- 每个网络有一个内置分组 All（builtin），建网时一起建。它的成员是全部节点，不写在成员表里。
CREATE TABLE groups (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    network_id BIGINT NOT NULL REFERENCES networks(id) ON DELETE CASCADE,
    name       TEXT NOT NULL,
    -- 比较用的写法（小写）：名字在一个网络里不分大小写唯一。按字节排序，不跟数据库的语言环境走。
    folded     TEXT COLLATE "C" NOT NULL,
    builtin    BOOLEAN NOT NULL,
    UNIQUE (network_id, folded)
);

CREATE TABLE nodes (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    network_id      BIGINT NOT NULL REFERENCES networks(id),
    public_key      BYTEA NOT NULL UNIQUE,
    name            TEXT NOT NULL,
    virtual_ip      BIGINT NOT NULL UNIQUE,
    hostname        TEXT NOT NULL,
    platform        TEXT NOT NULL,
    version         TEXT NOT NULL,
    declared        JSONB NOT NULL,
    forward_target  BOOLEAN NOT NULL,
    relay           JSONB,
    exit            JSONB,
    dial_out_only   BOOLEAN NOT NULL,
    routing         JSONB,
    reach           JSONB,
    pinned_relays   JSONB NOT NULL,
    profile         JSONB,
    auto_update     BOOLEAN NOT NULL,
    self_update     JSONB,
    update_failure  JSONB,
    endpoints       JSONB NOT NULL,
    local_addresses JSONB,
    observed        TEXT,
    attached        JSONB NOT NULL,
    relay_reach     JSONB NOT NULL,
    created_at      BIGINT NOT NULL,
    last_seen_at    BIGINT,
    netmap_version  BIGINT NOT NULL,
    netmap_digest   BYTEA,
    sent_version    BIGINT NOT NULL,
    acked_version   BIGINT NOT NULL,
    enrolled_with   BYTEA,
    UNIQUE (network_id, name)
);
CREATE INDEX nodes_by_network ON nodes(network_id);

CREATE TABLE group_members (
    group_id BIGINT NOT NULL REFERENCES groups(id) ON DELETE CASCADE,
    node_id  BIGINT NOT NULL REFERENCES nodes(id) ON DELETE CASCADE,
    PRIMARY KEY (group_id, node_id)
);
CREATE INDEX group_members_by_node ON group_members(node_id);

CREATE TABLE enroll_tokens (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    network_id   BIGINT NOT NULL REFERENCES networks(id) ON DELETE CASCADE,
    secret_hash  BYTEA NOT NULL UNIQUE,
    prefix       TEXT NOT NULL,
    created_at   BIGINT NOT NULL,
    expires_at   BIGINT NOT NULL,
    virtual_ip   BIGINT,
    successor_of BIGINT REFERENCES nodes(id) ON DELETE CASCADE,
    used_at      BIGINT,
    used_by      BIGINT REFERENCES nodes(id) ON DELETE SET NULL
);

CREATE TABLE token_groups (
    token_id BIGINT NOT NULL REFERENCES enroll_tokens(id) ON DELETE CASCADE,
    group_id BIGINT NOT NULL REFERENCES groups(id) ON DELETE CASCADE,
    PRIMARY KEY (token_id, group_id)
);

-- 用到某个分组的规则要先删掉，分组才删得了。
CREATE TABLE rules (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    network_id BIGINT NOT NULL REFERENCES networks(id) ON DELETE CASCADE,
    name       TEXT NOT NULL,
    src        BIGINT NOT NULL REFERENCES groups(id),
    dst        BIGINT NOT NULL REFERENCES groups(id),
    direction  JSONB NOT NULL,
    enabled    BOOLEAN NOT NULL
);

-- 出口节点被删掉之前，经它出去的代理先停用、去掉出口（Store::delete_node）。
CREATE TABLE proxies (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    node_id    BIGINT NOT NULL REFERENCES nodes(id) ON DELETE CASCADE,
    name       TEXT NOT NULL,
    bind       TEXT NOT NULL,
    protocol   JSONB NOT NULL,
    exit_id    BIGINT REFERENCES nodes(id),
    username   TEXT NOT NULL,
    password   TEXT NOT NULL,
    salt       BYTEA NOT NULL,
    enabled    BOOLEAN NOT NULL,
    allow_from JSONB NOT NULL,
    class      JSONB,
    optimistic BOOLEAN,
    lane       BOOLEAN NOT NULL,
    UNIQUE (node_id, name)
);

CREATE TABLE forwards (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    network_id     BIGINT NOT NULL REFERENCES networks(id) ON DELETE CASCADE,
    name           TEXT NOT NULL,
    protocol       JSONB NOT NULL,
    listen_node    BIGINT NOT NULL REFERENCES nodes(id) ON DELETE CASCADE,
    bind           TEXT NOT NULL,
    target_node    BIGINT NOT NULL REFERENCES nodes(id) ON DELETE CASCADE,
    target_addr    TEXT NOT NULL,
    allow_from     JSONB NOT NULL,
    enabled        BOOLEAN NOT NULL,
    class          JSONB,
    proxy_protocol JSONB
);

-- 一对节点只有一行，编号小的在前。
CREATE TABLE pair_settings (
    node_a     BIGINT NOT NULL REFERENCES nodes(id) ON DELETE CASCADE,
    node_b     BIGINT NOT NULL REFERENCES nodes(id) ON DELETE CASCADE,
    keep_alive BOOLEAN NOT NULL,
    congestion TEXT,
    PRIMARY KEY (node_a, node_b),
    CHECK (node_a < node_b)
);

-- 删掉的节点留下的虚拟 IP 和名字，到期之前不分给别的节点。
CREATE TABLE cooldowns (
    network_id BIGINT NOT NULL REFERENCES networks(id) ON DELETE CASCADE,
    kind       TEXT NOT NULL,
    value      TEXT NOT NULL,
    until      BIGINT NOT NULL,
    PRIMARY KEY (network_id, kind, value)
);

CREATE TABLE oplog (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    at         BIGINT NOT NULL,
    network_id BIGINT,
    action     TEXT NOT NULL,
    detail     TEXT NOT NULL,
    refs       JSONB NOT NULL,
    params     JSONB NOT NULL
);

CREATE TABLE tests (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    network_id BIGINT NOT NULL REFERENCES networks(id) ON DELETE CASCADE,
    node_a     BIGINT NOT NULL REFERENCES nodes(id) ON DELETE CASCADE,
    node_b     BIGINT NOT NULL REFERENCES nodes(id) ON DELETE CASCADE,
    started_at BIGINT NOT NULL,
    view       JSONB NOT NULL
);
CREATE INDEX tests_by_pair ON tests(network_id, node_a, node_b);

CREATE TABLE route_switches (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    network_id BIGINT NOT NULL REFERENCES networks(id) ON DELETE CASCADE,
    from_node  BIGINT NOT NULL REFERENCES nodes(id) ON DELETE CASCADE,
    to_node    BIGINT NOT NULL REFERENCES nodes(id) ON DELETE CASCADE,
    at         BIGINT NOT NULL,
    previous   JSONB NOT NULL,
    route      JSONB NOT NULL,
    cause      JSONB NOT NULL
);
CREATE INDEX route_switches_by_pair ON route_switches(network_id, from_node, to_node);

-- 每个点一行。node_id 是 0 表示整个网络的序列；它不是外键，节点删掉之后它的历史留到过期。
CREATE TABLE stats (
    network_id BIGINT NOT NULL REFERENCES networks(id) ON DELETE CASCADE,
    series     BIGINT NOT NULL,
    node_id    BIGINT NOT NULL,
    step       BIGINT NOT NULL,
    at         BIGINT NOT NULL,
    value      DOUBLE PRECISION NOT NULL,
    PRIMARY KEY (network_id, series, node_id, step, at)
);
