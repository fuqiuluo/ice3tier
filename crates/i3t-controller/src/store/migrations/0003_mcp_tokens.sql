-- 签给 AI Agent 的 MCP 令牌（JWT），和操作记录里"这是哪个令牌做的"。
--
-- 这里不存 JWT 本身，只存它的 jti 和签给了谁：验证时签名对、jti 在这张表里而且没被撤销才算数，
-- 所以换了一个库（恢复了更早的备份）之后，表里没有的 JWT 就不认。网络删掉时只限它的令牌一起删掉。
--
-- oplog.actor 是 NULL 表示管理员自己做的（管理令牌）、节点引起的或者 controller 自己做的。

CREATE TABLE mcp_tokens (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    jti        TEXT NOT NULL UNIQUE,
    name       TEXT NOT NULL,
    scopes     JSONB NOT NULL,
    network_id BIGINT REFERENCES networks(id) ON DELETE CASCADE,
    created_at BIGINT NOT NULL,
    expires_at BIGINT NOT NULL,
    revoked_at BIGINT
);

ALTER TABLE oplog ADD COLUMN actor JSONB;
